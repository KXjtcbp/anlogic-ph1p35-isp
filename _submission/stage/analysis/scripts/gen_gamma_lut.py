# -*- coding: utf-8 -*-
"""生成 FPGA 端「S 曲线 / 伽马」校正查找表（8bit -> 8bit，256 项）。

曲线定义（双伽马 S 曲线，端点与拐点精确可控）：
    设拐点 PIVOT = P（默认 118 = 画面中间调位置）
    x <= P :  y = P * (x/P)^A                      (A>1 => 暗部压暗)
    x >  P :  y = P + (255-P) * (1 - ((255-x)/(255-P))^B)   (B>1 => 高光提亮)
性质：y(0)=0、y(P)=P、y(255)=255、全程单调不减；A=B=1 时退化为恒等映射（即 bypass）。
A、B 就是「拐点处对比度增益」：1.25 => 中间调对比度 +25%。

浅阴影保护 TOE：x < TOE 时把 S 曲线与恒等映射按 x/TOE 权重线性混合，
避免 8bit 量化在极暗处被压出「平台阶」（合并码值级数）。

输出：
  <前缀>.mif    —— ERAM/ROM IP 初始化文件（Altera MIF 风格）
  <前缀>.coe    —— Xilinx COE 风格（部分工具的 ROM 向导要求这种）
  <前缀>.vh     —— 可直接粘进 Verilog 模块的 function（纯 ASCII 注释，零 IP 依赖）
  <前缀>.txt    —— 人类可读的完整表格 + 校验结论

用法：
  python gen_gamma_lut.py                        # 默认：P118 A1.25 B1.25 TOE16
  python gen_gamma_lut.py --pivot 128 --a 1.45 --b 1.45 --toe 0 --prefix gamma_strong
  python gen_gamma_lut.py --all                  # 一次生成推荐的两套表 + 打印对比
"""
import argparse
import math
import os
import sys

OUTDIR = os.path.dirname(os.path.abspath(__file__))


def s_curve(x, pivot=118, a=1.25, b=1.25, toe=16):
    """返回 0..255 的整数映射值（四舍五入）。"""
    if x <= 0:
        return 0
    if x >= 255:
        return 255
    if x <= pivot:
        y = pivot * (float(x) / pivot) ** a
    else:
        y = pivot + (255 - pivot) * (1.0 - ((255.0 - x) / (255 - pivot)) ** b)
    if toe > 0 and x < toe:
        w = float(x) / toe                      # 0 -> 恒等映射, 1 -> 纯 S 曲线
        y = x * (1.0 - w) + y * w
    return int(math.floor(y + 0.5))


def build(pivot=118, a=1.25, b=1.25, toe=16):
    return [s_curve(x, pivot, a, b, toe) for x in range(256)]


def check(tbl):
    """返回校验字典：单调性、端点、丢失码值级数、最大平段。"""
    mono = all(tbl[i] <= tbl[i + 1] for i in range(255))
    lost = 0
    flat_runs = []
    i = 0
    while i < 256:
        j = i
        while j + 1 < 256 and tbl[j + 1] == tbl[i]:
            j += 1
        if j > i:
            lost += (j - i)
            flat_runs.append((i, j, tbl[i]))
        i = j + 1
    used = len(set(tbl))
    return dict(monotone=mono, y0=tbl[0], y255=tbl[255], y_pivot=None,
                distinct=used, lost_levels=lost, max_flat=max([r[1] - r[0] + 1 for r in flat_runs] or [1]),
                flat_runs=flat_runs)


def write_mif(path, tbl, width=8):
    with open(path, 'w', encoding='ascii', newline='\n') as f:
        f.write('DEPTH=256;\nWIDTH=%d;\nADDRESS_RADIX=DEC;\nDATA_RADIX=HEX;\n'
                'CONTENT BEGIN\n' % width)
        for i, v in enumerate(tbl):
            f.write('    %d : %02X;\n' % (i, v))
        f.write('END;\n')


def write_coe(path, tbl):
    with open(path, 'w', encoding='ascii', newline='\n') as f:
        f.write('memory_initialization_radix=16;\n')
        f.write('memory_initialization_vector=\n')
        for i in range(0, 256, 16):
            f.write(','.join('%02X' % v for v in tbl[i:i + 16]))
            f.write(',\n' if i < 240 else ';\n')


def write_vh(path, tbl, name='f_gamma', pivot=118, a=1.25, b=1.25, toe=16):
    """纯 ASCII 注释，避免任何编码问题；函数体为完整 256 项 case。"""
    with open(path, 'w', encoding='ascii', newline='\n') as f:
        f.write('// -----------------------------------------------------------------------------\n')
        f.write('// %s : 8bit -> 8bit S-curve LUT (auto-generated by gen_gamma_lut.py)\n' % name)
        f.write('// PIVOT=%d  A=%.3f  B=%.3f  TOE=%d   ; A=B=1 degenerates to identity (bypass)\n'
                % (pivot, a, b, toe))
        f.write('// DO NOT EDIT BY HAND. Regenerate instead. No IP / no include dependency:\n')
        f.write('// paste this function inside the module that uses it.\n')
        f.write('// -----------------------------------------------------------------------------\n')
        f.write('function [7:0] %s;\n' % name)
        f.write('    input [7:0] x;\n')
        f.write('    begin\n')
        f.write('        case (x)\n')
        for i, v in enumerate(tbl):
            f.write('            8\'d%-3d : %s = 8\'d%d;\n' % (i, name, v))
        f.write('            default : %s = 8\'d0;\n' % name)
        f.write('        endcase\n')
        f.write('    end\n')
        f.write('endfunction\n')


def write_hex(path, tbl):
    """供 Verilog Testbench 用 $readmemh 读取的纯十六进制表（每行 2 位）。"""
    with open(path, 'w', encoding='ascii', newline='\n') as f:
        for v in tbl:
            f.write('%02x\n' % v)


def write_txt(path, tbl, args, ck):
    anchors = [0, 16, 64, 118, 128, 200, 255]
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('S 曲线查找表   PIVOT=%d  A=%.3f  B=%.3f  TOE=%d\n' % (args.pivot, args.a, args.b, args.toe))
        f.write('单调不减: %s    y(0)=%d    y(255)=%d    y(pivot)=%d\n'
                % (ck['monotone'], ck['y0'], ck['y255'], tbl[args.pivot]))
        f.write('8bit 可用级数: %d / 256   合并丢失级数: %d   最长平段: %d\n'
                % (ck['distinct'], ck['lost_levels'], ck['max_flat']))
        f.write('平段(码值区间 -> 输出): %s\n' % (ck['flat_runs'] if ck['flat_runs'] else '无'))
        f.write('\n锚点（Testbench 期望值）:\n')
        for x in anchors:
            if args.pivot <= x < 256:
                f.write('  %3d -> %3d   (%+d)\n' % (x, tbl[x], tbl[x] - x))
            else:
                f.write('  %3d -> %3d   (%+d)\n' % (x, tbl[x], tbl[x] - x))
        f.write('\n完整表格（每行 16 项；列 = 输入 x，值 = 输出 y）:\n')
        for i in range(0, 256, 16):
            f.write('%3d: ' % i + ' '.join('%3d' % v for v in tbl[i:i + 16]) + '\n')
        f.write('\n矩阵（行=x/16，列=x%16）:\n')
        f.write('     ' + ''.join('%4d' % c for c in range(16)) + '\n')
        for r in range(16):
            f.write('%3d| ' % (r * 16) + ''.join('%4d' % tbl[r * 16 + c] for c in range(16)) + '\n')


def report(tbl, pivot, a, b, toe, tag):
    ck = check(tbl)
    ck['y_pivot'] = tbl[pivot]
    print('--- %s : PIVOT=%d A=%.3f B=%.3f TOE=%d ---' % (tag, pivot, a, b, toe))
    print('  锚点: ' + '  '.join('%d->%d' % (x, tbl[x]) for x in (0, 16, 64, 118, 128, 200, 255)))
    print('  单调不减=%s  y(0)=%d y(255)=%d y(%d)=%d  可用级数=%d/256  丢失级数=%d  最长平段=%d'
          % (ck['monotone'], ck['y0'], ck['y255'], pivot, ck['y_pivot'],
             ck['distinct'], ck['lost_levels'], ck['max_flat']))
    print('  对比度: 暗部(64) %+d 码, 高光(200) %+d 码' % (tbl[64] - 64, tbl[200] - 200))
    return ck


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--pivot', type=int, default=118)
    ap.add_argument('--a', type=float, default=1.25)
    ap.add_argument('--b', type=float, default=1.25)
    ap.add_argument('--toe', type=int, default=0)
    ap.add_argument('--prefix', type=str, default='gamma_lut_p118_k125')
    ap.add_argument('--all', action='store_true')
    args = ap.parse_args()

    if args.all:
        variants = [(118, 1.25, 1.25, 0, 'gamma_lut_p118_k125', 'f_gamma'),
                    (128, 1.45, 1.45, 0, 'gamma_lut_p128_k145', 'f_gamma_strong'),
                    (118, 1.25, 1.25, 16, 'gamma_lut_p118_k125_toe16', 'f_gamma_toe16')]
        for p, a, b, t, pre, fname in variants:
            tbl = build(p, a, b, t)
            ck = report(tbl, p, a, b, t, pre)
            write_mif(os.path.join(OUTDIR, pre + '.mif'), tbl)
            write_coe(os.path.join(OUTDIR, pre + '.coe'), tbl)
            write_hex(os.path.join(OUTDIR, pre + '.hex'), tbl)
            write_vh(os.path.join(OUTDIR, pre + '.vh'), tbl, fname, p, a, b, t)
            write_txt(os.path.join(OUTDIR, pre + '.txt'), tbl, args if (p, a, b, t) ==
                      (args.pivot, args.a, args.b, args.toe) else
                      argparse.Namespace(pivot=p, a=a, b=b, toe=t), ck)
            print('  已写出 %s.{mif,coe,vh,txt}' % pre)
        return

    tbl = build(args.pivot, args.a, args.b, args.toe)
    ck = report(tbl, args.pivot, args.a, args.b, args.toe, args.prefix)
    write_mif(os.path.join(OUTDIR, args.prefix + '.mif'), tbl)
    write_coe(os.path.join(OUTDIR, args.prefix + '.coe'), tbl)
    write_vh(os.path.join(OUTDIR, args.prefix + '.vh'), tbl, 'f_gamma',
             args.pivot, args.a, args.b, args.toe)
    write_txt(os.path.join(OUTDIR, args.prefix + '.txt'), tbl, args, ck)
    print('已写出 %s.{mif,coe,vh,txt} 到 %s' % (args.prefix, OUTDIR))


if __name__ == '__main__':
    main()
