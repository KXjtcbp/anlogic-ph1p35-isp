def make_table(doc, headers, rows, widths, font_size=10.5, header_bg="EDF1F7"):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False

    # 固定布局
    tblpr = t._tbl.tblPr
    layout = tblpr.makeelement(qn("w:tblLayout"), {})
    layout.set(qn("w:type"), "fixed")
    tblpr.append(layout)
    tw = tblpr.makeelement(qn("w:tblW"), {})
    tw.set(qn("w:w"), str(int(sum(widths) * 567)))
    tw.set(qn("w:type"), "dxa")
    tblpr.append(tw)

    # tblGrid
    grid = t._tbl.find(qn("w:tblGrid"))
    if grid is not None:
        t._tbl.remove(grid)
    grid = t._tbl.makeelement(qn("w:tblGrid"), {})
    for w in widths:
        gc = grid.makeelement(qn("w:gridCol"), {})
        gc.set(qn("w:w"), str(int(w * 567)))
        grid.append(gc)
    tblpr.addnext(grid)

    def fill(cell, text, w, bold=False, bg=None, size=font_size):
        cell.width = Cm(w)
        p = cell.paragraphs[0]
        pf = p.paragraph_format
        pf.line_spacing = 1.25
        pf.space_before = Pt(2)
        pf.space_after = Pt(2)
        set_run(p.add_run(text), size=size, bold=bold)
        if bg:
            tcpr = cell._tc.get_or_add_tcPr()
            shd = tcpr.makeelement(qn("w:shd"), {})
            shd.set(qn("w:val"), "clear")
            shd.set(qn("w:fill"), bg)
            tcpr.append(shd)

    for i, htxt in enumerate(headers):
        fill(t.rows[0].cells[i], htxt, widths[i], bold=True, bg=header_bg)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            fill(cells[i], val, widths[i])
    return t


