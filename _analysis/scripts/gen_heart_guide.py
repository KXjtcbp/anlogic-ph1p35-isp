def st(p, cs="宋体", en="Times New Roman", size=12, bold=False, color=None):
    for r in p.runs:
        r.font.name = en
        r.font.size = Pt(size)
        r.font.bold = bold
        rPr = r._element.get_or_add_rPr()
        rf = rPr.find(qn("w:rFonts"))
        if rf is None:
            rf = rPr.makeelement(qn("w:rFonts"), {})
            rPr.append(rf)
        rf.set(qn("w:ascii"), en)
        rf.set(qn("w:hAnsi"), en)
        rf.set(qn("w:eastAsia"), cs)
        if color:
            r.font.color.rgb = color
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)


def H(t, lv=1):
    p = d.add_paragraph()
