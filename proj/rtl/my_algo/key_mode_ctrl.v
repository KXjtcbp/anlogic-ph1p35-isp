//===========================================================================
//  key_mode_ctrl.v  --  按键算法模式切换控制器
//
//  项目：2026 全国大学生嵌入式芯片与系统设计竞赛 选题二
//
//  作用：把开发板上的一个按键变成「算法模式切换键」，
//        每按一次在 5 种模式之间循环：
//            MODE 0(原图) → MODE 1(灰度) → MODE 2(伪彩热力图)
//            → MODE 3(二值化) → MODE 4(卡通化) → 回到 0
//
//  ---------------------------------------------------------------------
//  按键硬件事实（来自 user_source/constraints_source/pin.adc）
//  ---------------------------------------------------------------------
//    set_pin_assignment { I_button[0] } { LOCATION = N2;  ... PULLTYPE = PULLUP; }
//    set_pin_assignment { I_button[1] } { LOCATION = J14; ... PULLTYPE = PULLUP; }
//  即按键带内部上拉、按下为低电平（active-low）。
//
//  ---------------------------------------------------------------------
//  为什么单独例化一份消抖而不是复用现成的
//  ---------------------------------------------------------------------
//   工程里 key_remove_shakes 只被 hdmi_tx.v:141 内部使用（它的 I_key_in 在
//   design_top_wrapper.v:768 被接成 1'b0，等于没用）。本模块自己例化一份，
//   互不干扰，不会改变 hdmi_tx 的任何既有行为。
//
//  ---------------------------------------------------------------------
//  时钟域
//  ---------------------------------------------------------------------
//   必须用 24 MHz（S_24m_clk）等慢时钟，不要用 csi_rx_clk/hdmi 时钟：
//   key_remove_shakes 内部固定计数到 100000，
//   在 24 MHz 下约 4.2 ms（正常消抖），在 100 MHz 下只有 1 ms（偏短）。
//
//  资源消耗估计：~40 slice（一个 17 bit 计数器 + 几个同步器，可忽略）
//===========================================================================

//  ---------------------------------------------------------------------
//  跨时钟域协议（重要，别改回 2 bit 直连）
//  ---------------------------------------------------------------------
//   本模块跑在 24 MHz 慢时钟域；算法模式要送给 hdmi_mixer（75 MHz 像素域）
//   和 my_algo（csi_rx_clk 域）。**只把 2 bit 模式值直接送过去会被时序工具
//   当成跨域组合路径**，实测代价：
//     - 直连进 hdmi_mixer 组合云：Setup WNS 由 +0.103ns 掉到 -4.416ns（29 个违例端点）
//     - 只加同步器送电平：      仍有 -0.085ns / 2 个违例端点
//   因此改为标准做法：**只跨 1 bit 的"翻转"信号**。
//     O_mode_tgl 每次按键翻转一次 → 目标域同步后做边沿检测 → 在目标域本地计数。
//   好处：单 bit 翻转不存在多 bit 同时变化导致的不一致采样问题；
//         跨域那条路的起点是慢域寄存器，中间没有组合逻辑，天然满足时序。
//   注意：O_mode / O_mode_chg 只供同域使用（本工程里 O_mode 现在没有外部负载，
//         算法模式值由各目标域各自计数得到）。
//   模式数由 4 改为 5 之后，单 bit 翻转不够用了（0..4 需要 3 bit 计数，
//   且要保证两个接收域的模 5 计数器严格同步），因此增加第二根翻转线：
//     O_mode_tgl  —— 每次按键翻转一次（和原来完全一样）
//     O_mode_wrap —— 计数由 4 回到 0 的那一次额外翻转一次
//   两个接收域各自维护 3 bit 计数器：
//     收到 tgl  边沿 → mode = (mode == 4) ? 0 : mode + 1
//     收到 wrap 边沿 → mode = 0
//   这样即使某一域漏掉一次 tgl 事件，也会在下一次 wrap 时被拉回同步，
//   而两根线各自仍是单 bit 翻转、起点是慢域寄存器、中间无组合逻辑，
//   与原来那根线一样满足跨域时序。
//===========================================================================

module key_mode_ctrl (
    input  wire       I_clk     ,   // 24 MHz 慢时钟
    input  wire       I_rst_n   ,
    input  wire       I_key_n   ,   // 按键输入，active-low（带内部上拉）
    output reg  [2:0] O_mode    ,   // 本域当前算法模式（同域使用）
    output reg        O_mode_chg,   // 模式变化时给出 1 个时钟周期的高脉冲（同域使用）
    output reg        O_mode_tgl,   // ★跨域用★：每次按键翻转 1 次（单 bit）
    output reg        O_mode_wrap   // ★跨域用★：模式由 4 回到 0 时翻转 1 次（单 bit）
);

    // 按键消抖：每次有效按下产生 1 个时钟周期的高脉冲
    wire S_key_trig;

    key_remove_shakes u_key_remove_shakes_mode (
        .I_clk          ( I_clk      ),
        .I_rst_n        ( I_rst_n    ),
        .I_key_in       ( I_key_n    ),
        .O_key_trig_out ( S_key_trig )
    );

    // 消抖后的按键脉冲先同步到本域再打一拍，得到"干净的单拍脉冲"，
    // 避免直接拿它去翻转跨域信号（可能带毛刺）。
    reg S_key_trig_d;

    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n) begin
            O_mode     <= 3'd2;      // 上电默认伪彩热力图（上电即有算法效果）
            O_mode_chg <= 1'b0;
            O_mode_tgl <= 1'b0;
            O_mode_wrap<= 1'b0;
            S_key_trig_d <= 1'b0;
        end
        else begin
            S_key_trig_d <= S_key_trig;
            O_mode_chg   <= S_key_trig_d;          // 同域单拍脉冲
            if(S_key_trig_d) begin
                // 0→1→2→3→4→0 循环
                if(O_mode == 3'd4) begin
                    O_mode      <= 3'd0;
                    O_mode_wrap <= ~O_mode_wrap;   // ★只在回卷那一次翻第二根线★
                end
                else begin
                    O_mode <= O_mode + 3'd1;
                end
                O_mode_tgl <= ~O_mode_tgl;         // ★每次按键都翻这 1 bit★
            end
        end
    end

endmodule
