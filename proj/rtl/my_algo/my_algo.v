//===========================================================================
//  my_algo.v  --  自研图像增强模块「RGB 点运算算法集」
//
//  项目：2026 全国大学生嵌入式芯片与系统设计竞赛 选题二
//  平台：安路 PH1P35 (HX1P35A) + SC500CS + DDR2 + HDMI 720p60
//
//  插入位置：user_source/hdl_source/isp/isp_top.v
//            —— 接在 awb 之后、data_96bit_to_128bit 之前
//
//  ---------------------------------------------------------------------
//  一、数据格式（已由三处源码交叉验证，务必不要改）
//  ---------------------------------------------------------------------
//   96 bit = 4 个像素 × 24 bit
//     像素0 = I_tdata[95:72]  像素1 = I_tdata[71:48]
//     像素2 = I_tdata[47:24]  像素3 = I_tdata[23:0]
//   每像素 24 bit = {R[7:0], G[7:0], B[7:0]}
//     即 [23:16]=R  [15:8]=G  [7:0]=B
//   依据：
//     isp/data128_96/data128_96.v:16   O_tdata = {I_tdata[23:0], I_tdata[55:32],
//                                                 I_tdata[87:64], I_tdata[119:96]}
//     isp/edge_detect_96.v:22-25       pix0=[95:72] ... pix3=[23:0]
//     isp/data96_128/data96_128.v:96   {{8'd0},I_tdata[95:72], ... ,{8'd0},I_tdata[23:0]}
//   一个 beat 只有 4 个像素 —— 原厂 edge_detect_96 也是按 4 像素处理的。
//
//  ---------------------------------------------------------------------
//  二、端口方向（照抄原厂 edge_detect_96.v，I_tready 是"输出"、O_tready 是"输入"）
//  ---------------------------------------------------------------------
//   这是原例程的反向命名习惯，不要"纠正"成常规写法，
//   否则 isp_top 的 wire 连接会全部对不上。
//
//  ---------------------------------------------------------------------
//  三、本模块的算法内容（与参考例程 edge_detect_96.v 完全不同源）
//  ---------------------------------------------------------------------
//   参考例程做的是 Sobel 空间域边缘检测（需 2 个行缓存）；
//   本模块做的是点运算 + 一维相邻像素梯度（无行缓存），共 5 种模式：
//     MODE 0  原图直通           —— 用于 A/B 对照演示
//     MODE 1  BT.601 灰度        —— Y = (77R + 150G + 29B) >> 8
//     MODE 2  伪彩热力图         —— Y 五段线性映射：蓝→青→绿→黄→红
//     MODE 3  亮度五档彩条       —— Y 固定5段阈值(32/64/128/192)映射黑/蓝/绿/黄/红
//     MODE 4  ★卡通化★           —— 亮度四级平涂（区域填充）+ 相邻像素差描边
//   五种模式均由按键实时切换（见 key_mode_ctrl.v），
//   切到 MODE 0 就是原图，可现场做"开/关算法"的对比演示。
//
//  ---------------------------------------------------------------------
//  四、时序与资源纪律
//  ---------------------------------------------------------------------
//   1. 单级打拍（与 edge_detect_96.v 相同）：O_tdata/O_tlast/O_tuser/O_tvalid
//      同步延迟 1 拍。若以后再加流水线级数，这四个信号必须一起延。
//   2. 纯点运算 + 一维相邻像素梯度，无行缓存、无除法器 —— slice 消耗预计 +150~350。
//      MODE 4 卡通化只引入「上一拍 pix3 亮度 + 有效标志」共 9 个寄存器，
//      不引入 ERAM 行缓存（75 MHz 像素域余量只剩 0.110 ns，行缓存地址逻辑风险高）。
//   3. ex3 底板 Setup WNS 只剩 +0.103 ns（最紧路径在 HDMI_SERIAL_CLK，
//      375 MHz / 2.667 ns）。本模块跑在 csi_rx_clk 域（约 100 MHz），
//      点运算的组合深度只有 2~3 级 LUT，不会成为新的关键路径；
//      但每次改动仍必须重看 route.qor 的 Setup WNS。
//   4. 所有运算位宽显式声明，每个通道最后都截回 8 bit，禁止隐式位宽转换。
//      教训：上一版用 (y-51)<<2 得到 9 bit 中间值拼进 24 bit 输出会爆到 30 bit。
//
//===========================================================================

module my_algo #(
    parameter [7:0] THRESH    = 8'd128,   // MODE3 二值化阈值
    parameter [2:0] MODE_INIT = 3'd2,     // 上电默认模式（2 = 伪彩热力图）
    parameter [7:0] T_EDGE    = 8'd48     // MODE4 卡通描边阈值（相邻像素亮度差）
)(
    input  wire         I_clk    ,
    input  wire         I_rst_n  ,
    input  wire         I_tlast  ,
    input  wire         I_tuser  ,
    input  wire [95:0]  I_tdata  ,
    input  wire         I_tvalid ,
    output wire         I_tready ,
    output reg  [95:0]  O_tdata  ,
    output reg          O_tlast  ,
    output reg          O_tuser  ,
    output reg          O_tvalid ,
    input  wire         O_tready ,
    // 运行时算法选择（来自按键，异步信号，此处只使用，切换时机无需严格控制）
    // 3 bit = 5 种模式（0 直通 / 1 灰度 / 2 伪彩 / 3 二值 / 4 卡通）
    input  wire [2:0]   I_mode
);

    //------------------------------------------------------------------
    // 无背压：与 edge_detect_96.v 的 assign O_tready = I_tready; 等价
    //------------------------------------------------------------------
    assign I_tready = O_tready;

    //------------------------------------------------------------------
    // [CDC] I_mode 来自 24 MHz 按键时钟域（key_mode_ctrl），本模块跑在
    //       csi_rx_clk 域。加 2 级同步器消除亚稳态（只花 4 个寄存器）。
    //       mode 只在按键时变化，且变化后要等下一帧才可能被肉眼看到，
    //       所以这里只要"不产生亚稳态"即可，不需要握手。
    //------------------------------------------------------------------
    reg [2:0] S_mode_sync1;
    reg [2:0] S_mode_sync2;
    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n) begin
            S_mode_sync1 <= MODE_INIT;
            S_mode_sync2 <= MODE_INIT;
        end
        else begin
            S_mode_sync1 <= I_mode;
            S_mode_sync2 <= S_mode_sync1;
        end
    end
    wire [2:0] S_mode = S_mode_sync2;

    //------------------------------------------------------------------
    // 取 4 个像素
    //------------------------------------------------------------------
    wire [23:0] pix0 = I_tdata[95:72];
    wire [23:0] pix1 = I_tdata[71:48];
    wire [23:0] pix2 = I_tdata[47:24];
    wire [23:0] pix3 = I_tdata[23:0];

    //==================================================================
    //  函数 1：BT.601 亮度
    //  Y = (77R + 150G + 29B) >> 8
    //
    //  这里刻意用「移位 + 加法」手写常数乘法，不用 `r * 77` 这种写法。
    //  原因（实测数据）：写成 r*77 / g*150 / b*29 时，TD 会把每个常数乘法
    //  综合成一个 DSP 硬核乘法器 —— 4 个像素 × 3 个乘法 + 伪彩里的 d*5，
    //  直接把整机 DSP 从 9 个顶到 40/40 用满；而 DSP 用满之后，hdmi_mixer
    //  里原本能用 DSP 的那条乘法路径被迫改用 LUT+加法实现，出现
    //  5 个 HDMI 像素域时序违例（0.018~0.081ns）。
    //  手写成移位加法后不再推断 DSP，代价是 LUT/加法器（LUT 还剩 40% 余量）。
    //  中间和最大 255*256 = 65280 < 2^17，用 17 bit 承接绝对安全。
    //==================================================================
    function [7:0] f_luma;
        input [7:0] r;
        input [7:0] g;
        input [7:0] b;
        reg   [16:0] s;
        begin
            s      = {r, 6'd0};                    // R*64
            s      = s + {2'd0, r, 3'd0};          // + R*8
            s      = s + {4'd0, r, 2'd0};          // + R*4
            s      = s + {8'd0, r};                // + R      → 77R
            s      = s + {g, 7'd0};                // + G*128
            s      = s + {3'd0, g, 3'd0};          // + G*16
            s      = s + {5'd0, g, 1'b0};          // + G*4
            s      = s + {7'd0, g, 1'b0};          // + G*2    → 150G
            s      = s + {3'd0, b, 4'd0};          // + B*16
            s      = s + {4'd0, b, 3'd0};          // + B*8   ★2026-10-06补：原版漏了这一项
            s      = s + {6'd0, b, 2'd0};          // + B*4
            s      = s + {8'd0, b};                // + B     → 16+8+4+1 = 29B ✓
            f_luma = s[15:8];
        end
    endfunction

    //==================================================================
    //  函数 2：伪彩热力图查找表（蓝 → 青 → 绿 → 黄 → 红，五段线性）
    //  为了省 LUT，斜率写成"每 50 级步进 5"，共用同一个步进量
    //  每一段都显式 & 8'hFF 截回 8 bit，防止拼接宽度膨胀
    //
    //  ★ d*5 必须手写成 (d<<2)+d，不能写 `d * 8'd5`：
    //    写成乘法号时 TD 会给每个像素推断一个 DSP 乘法器（4 像素 × 5 段分支），
    //    这是 DSP 被顶满 40/40 的另一半原因。写成移位加法后只用 1 个 9bit 加法器。
    //==================================================================
    function [23:0] f_heat;
        input [7:0] y;
        reg   [7:0] d;      // 段内偏移 0..50
        reg   [8:0] e;      // d*5 的中间结果（最大 250，9 bit）
        reg   [7:0] s5;     // d*5 截回 8 bit
        reg   [7:0] r;
        reg   [7:0] g;
        reg   [7:0] b;
        begin
            // ★ 绝不在这里读 d/e/s5 做"占位"！
            //   TD 会报：HDL-7215 use of 'd' without initialization in static subprogram
            //            HDL-5369 latch inferred for net 'f_heat.d[7]'
            //            HDL-8007 ERROR: net 'f_heat.d[7]' is constantly driven from multiple places
            //   而 my_algo 整模块会被降级成 black box（HDL-1007）。
            //   教训：open_project 的"语法/接口分析"不做 elaborate 驱动检查，
            //        这类错误只有真正综合(run)时才暴露。
            //   因此每个分支都独立完整地给 d / e / s5 / r / g / b 赋值，一次都不预读。
            if(y < 8'd51) begin
                // 段 0：0..50   → 蓝通道 0..250，红绿=0
                d  = y;
                e  = ({1'b0, d} << 2) + {1'b0, d};
                s5 = e[7:0];
                r = 8'h00;                       g = 8'h00;                       b = s5;
            end
            else if(y < 8'd102) begin
                // 段 1：51..101 → 蓝 255 → 0，红绿=0
                d  = y - 8'd51;
                e  = ({1'b0, d} << 2) + {1'b0, d};
                s5 = e[7:0];
                r = 8'h00;                       g = 8'h00;                       b = 8'd255 - s5;
            end
            else if(y < 8'd153) begin
                // 段 2：102..152 → 绿 0 → 255，蓝=255
                d  = y - 8'd102;
                e  = ({1'b0, d} << 2) + {1'b0, d};
                s5 = e[7:0];
                r = 8'h00;                       g = s5;                          b = 8'hff;
            end
            else if(y < 8'd204) begin
                // 段 3：153..203 → 红 0 → 255，绿=255
                d  = y - 8'd153;
                e  = ({1'b0, d} << 2) + {1'b0, d};
                s5 = e[7:0];
                r = s5;                          g = 8'hff;                       b = 8'h00;
            end
            else begin
                // 段 4：204..255 → 绿 255 → 0，红=255，蓝=0
                d  = y - 8'd204;
                e  = ({1'b0, d} << 2) + {1'b0, d};
                s5 = e[7:0];
                r = 8'hff;                       g = 8'd255 - s5;                 b = 8'h00;
            end
            f_heat = {r, g, b};
        end
    endfunction

    //==================================================================
    //  函数 3：带符号保护的绝对差 |a-b|
    //    差值范围 -255..+255，用 9 bit 有符号承接，
    //    取低 8 bit 得到 0..255 —— 结果仍是 8 bit，便于和 T_EDGE 比较。
    //==================================================================
    function [7:0] f_absdiff;
        input [7:0] a;
        input [7:0] b;
        reg   [8:0] d;
        begin
            d = ({1'b0, a} - {1'b0, b});
            if(d[8]) f_absdiff = (~d[7:0]) + 8'd1;
            else     f_absdiff =   d[7:0];
        end
    endfunction

    //==================================================================
    //  函数 4：两个 8 bit 取较大值（用于把 beat 内 3 个梯度 + 跨 beat 1 个梯度合并）
    //==================================================================
    function [7:0] f_max2;
        input [7:0] a;
        input [7:0] b;
        begin
            f_max2 = (a > b) ? a : b;
        end
    endfunction

    //==================================================================
    //  函数 5：MODE 4 卡通化的「区域填充」部分 —— 亮度四级色调量化
    //  卡通化的两个组成部分：
    //    (a) 区域填充 = 把连续亮度压成少数几个平涂色块（本函数）
    //    (b) 边缘描边 = 相邻像素亮度差超过 T_EDGE 时画黑线（在 f_pixel 里）
    //  ★ 与参考例程 edge_detect_96.v 的 Sobel 完全不同源：
    //    参考例程输出的是「梯度强度灰度图」（单一通道、无行缓存之外的处理）；
    //    本函数输出的是「四级平涂色块」，描边只是叠加在其上的二值黑线。
    //    对外表现：参考例程=边缘亮线 + 其余全黑；本模块=彩色色块 + 黑描边。
    //  ★ 与 f_heat 同样的纪律：每个分支都独立完整地给 r/g/b 赋值，
    //    绝不预读任何局部变量，否则 TD 会报 HDL-8007 并把模块降级成 black box。
    //==================================================================
    function [23:0] f_cart;
        input [7:0] y;
        begin
            if(y < 8'd64)       f_cart = 24'h101020;   // 最暗 → 深蓝黑
            else if(y < 8'd128) f_cart = 24'h006090;   // 暗   → 蓝
            else if(y < 8'd192) f_cart = 24'h6ca03c;   // 亮   → 黄绿
            else                f_cart = 24'he6d296;   // 最亮 → 米白
        end
    endfunction

    //==================================================================
    //  函数 6：单像素分派（mode 与 edg 都由已打拍/已同步的信号驱动）
    //==================================================================
    function [23:0] f_pixel;
        input [23:0] p;
        input [2:0]  mode;
        input        edg;
        reg   [7:0]  y;
        begin
            y = f_luma(p[23:16], p[15:8], p[7:0]);
            case(mode)
                3'd0: f_pixel = p;                                     // 原图直通
                3'd1: f_pixel = {y, y, y};                             // 灰度
                3'd2: f_pixel = f_heat(y);                             // 伪彩热力图
                // MODE 3：固定 5 段阈值彩条（诊断用「看得见的直方图」）
                //   档0 黑 =   0.. 31   档1 蓝 =  32.. 63   档2 绿 =  64..127
                //   档3 黄 = 128..191   档4 红 = 192..255
                // 遮住镜头时整屏单色 ⇒ 直接读出黑电平基座落在哪一档。
                // （原为 (y > THRESH) ? 白 : 黑 二值化，THRESH 参数因此暂时未被使用）
                3'd3: f_pixel = (y <  8'd32) ? 24'h000000 :
                                (y <  8'd64) ? 24'h0000ff :
                                (y < 8'd128) ? 24'h00ff00 :
                                (y < 8'd192) ? 24'hffff00 :
                                               24'hff0000 ;
                3'd4: f_pixel = edg ? 24'h000000 : f_cart(y);          // ★卡通化
                default: f_pixel = p;
            endcase
        end
    endfunction

    //==================================================================
    //  MODE 4 描边所需的「上一拍亮度尾巴」
    //  原因：像素在 96 bit 里是 4 个一组（beat），beat 之间是连续的。
    //        pix0 的前一个像素其实就是上一拍的 pix3，所以只要记住
    //        上一拍的 pix3 亮度 + 一个「该亮度是否有效」的标志，
    //        就能在没有行缓存的情况下多抓到一条相邻像素差。
    //  为什么不用行缓存：本工程 75 MHz 像素域只剩 0.110 ns 余量，
    //       引入 ERAM 行缓存会把关键路径搬到行缓存地址逻辑上（风险高）。
    //       本方案只多花约 41 个寄存器 + 少量比较器。
    //==================================================================
    reg  [7:0] S_y3_pre;
    reg        S_prev_vld;

    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n) begin
            S_y3_pre   <= 8'd0;
            S_prev_vld <= 1'b0;
        end
        else begin
            S_y3_pre   <= 0;
            S_prev_vld <= 1'b0;
            if(I_tvalid) begin
                // 注意这里用的是输入侧 pix3 的亮度，和 S_data_next 同一拍
                S_y3_pre   <= f_luma(pix3[23:16], pix3[15:8], pix3[7:0]);
                // 行首/帧首没有「有效的前一像素」，此处不算描边，避免水平处出现假黑线
                S_prev_vld <= ~(I_tlast | I_tuser);
            end
        end
    end

    // 当前 beat 四个像素的亮度（组合）
    wire [7:0] S_y0 = f_luma(pix0[23:16], pix0[15:8], pix0[7:0]);
    wire [7:0] S_y1 = f_luma(pix1[23:16], pix1[15:8], pix1[7:0]);
    wire [7:0] S_y2 = f_luma(pix2[23:16], pix2[15:8], pix2[7:0]);
    wire [7:0] S_y3 = f_luma(pix3[23:16], pix3[15:8], pix3[7:0]);

    // 四个相邻像素梯度：beat 内 3 条 + 跨 beat 1 条
    wire [7:0] S_g01 = f_absdiff(S_y0, S_y1);
    wire [7:0] S_g12 = f_absdiff(S_y1, S_y2);
    wire [7:0] S_g23 = f_absdiff(S_y2, S_y3);
    wire [7:0] S_gp0 = f_absdiff(S_y3_pre, S_y0);

    // 每个像素的描边判定：参与它相邻的两个梯度中只要有一个越阈值就画线
    //   像素0：跨 beat 的 Sp0（仅在 S_prev_vld 有效时才参考）+ beat 内的 g01
    //   像素3：beat 内的 g23（右边邻居在下一拍，留给下一拍的像素0判定）
    wire S_e0 = ((S_gp0 > T_EDGE) && S_prev_vld) || (S_g01 > T_EDGE);
    wire S_e1 = (S_g01 > T_EDGE) || (S_g12 > T_EDGE);
    wire S_e2 = (S_g12 > T_EDGE) || (S_g23 > T_EDGE);
    wire S_e3 = (S_g23 > T_EDGE);

    wire [23:0] o_pix0 = f_pixel(pix0, S_mode, S_e0);
    wire [23:0] o_pix1 = f_pixel(pix1, S_mode, S_e1);
    wire [23:0] o_pix2 = f_pixel(pix2, S_mode, S_e2);
    wire [23:0] o_pix3 = f_pixel(pix3, S_mode, S_e3);

    wire [95:0] S_data_next = {o_pix0, o_pix1, o_pix2, o_pix3};

    //==================================================================
    //  单级流水打拍：数据与三个标记严格同拍
    //  （I_mode 由按键产生，可能带毛刺，但只在人眼可辨的帧边界附近变化，
    //    不做跨时钟同步；若以后要严格控制，可加一级 mode 寄存器）
    //==================================================================
    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n) begin
            O_tdata  <= 96'd0;
            O_tlast  <= 1'b0;
            O_tuser  <= 1'b0;
            O_tvalid <= 1'b0;
        end
        else begin
            O_tdata  <= S_data_next;
            O_tlast  <= I_tlast;
            O_tuser  <= I_tuser;
            O_tvalid <= I_tvalid;
        end
    end

endmodule
