    mem_b00[248] = 8'hfa; mem_b00[249] = 8'hfb; mem_b00[250] = 8'hfb; mem_b00[251] = 8'hfc;
    mem_b00[252] = 8'hfd; mem_b00[253] = 8'hfe; mem_b00[254] = 8'hfe; mem_b00[255] = 8'hff;
    //---- 其余 11 张表整体复制 mem_b00（12 路严格同表）----
    for (k = 0; k < 256; k = k + 1) begin
        mem_b01[k] = mem_b00[k];   mem_b02[k] = mem_b00[k];   mem_b03[k] = mem_b00[k];
        mem_b04[k] = mem_b00[k];   mem_b05[k] = mem_b00[k];   mem_b06[k] = mem_b00[k];
        mem_b07[k] = mem_b00[k];   mem_b08[k] = mem_b00[k];   mem_b09[k] = mem_b00[k];
        mem_b10[k] = mem_b00[k];   mem_b11[k] = mem_b00[k];
    end
end

// 3. 第 1 级：同步读 ROM（无条件、无使能、无复位 —— ERAM 最标准的读写法）
//    同时把输入数据/有效位/旁路位打一拍，保证与 rom_q 同相位。
//=============================================================================
reg [95:0] rom_q;   // 查表结果（第 1 级）
reg [95:0] d1;      // 与 rom_q 同拍的「原数据」，供旁路用
reg        v1, l1, u1, b1;

always @(posedge I_clk) begin
    rom_q[7:0]   <= mem_b00[I_tdata[7:0]];
    rom_q[15:8]  <= mem_b01[I_tdata[15:8]];
    rom_q[23:16] <= mem_b02[I_tdata[23:16]];
    rom_q[31:24] <= mem_b03[I_tdata[31:24]];
    rom_q[39:32] <= mem_b04[I_tdata[39:32]];
    rom_q[47:40] <= mem_b05[I_tdata[47:40]];
    rom_q[55:48] <= mem_b06[I_tdata[55:48]];
    rom_q[63:56] <= mem_b07[I_tdata[63:56]];
    rom_q[71:64] <= mem_b08[I_tdata[71:64]];
    rom_q[79:72] <= mem_b09[I_tdata[79:72]];
    rom_q[87:80] <= mem_b10[I_tdata[87:80]];
    rom_q[95:88] <= mem_b11[I_tdata[95:88]];
end

always @(posedge I_clk) begin
    d1 <= I_tdata;
    v1 <= I_tvalid;
    l1 <= I_tlast;
    u1 <= I_tuser;
    b1 <= I_gamma_bypass;
end

//=============================================================================
// 4. 第 2 级：输出寄存器（无条件推进）
//    ★照抄 awb.v:513 / my_algo.v:96 的 tready 直通写法：全链路无真反压，
//      本级绝不能停拍（停拍必丢 beat）。
//=============================================================================
reg [95:0] q2;
reg        v2, l2, u2;

assign I_tready = O_tready;        // 与 awb.v:513 / my_algo.v:96 完全一致

always @(posedge I_clk or negedge I_rst_n) begin
    if (!I_rst_n) begin
        v2 <= 1'b0;
        l2 <= 1'b0;
        u2 <= 1'b0;
        q2 <= 96'd0;
    end
    else begin
        v2 <= v1;
        l2 <= l1;
        u2 <= u1;
        q2 <= b1 ? d1 : rom_q;     // 旁路：整级直通（延迟仍是 2 拍）
    end
end

assign O_tdata  = q2;
assign O_tvalid = v2;
assign O_tlast  = l2;
assign O_tuser  = u2;

endmodule
