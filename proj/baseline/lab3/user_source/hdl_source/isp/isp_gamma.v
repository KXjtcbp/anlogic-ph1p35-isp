//   2026-10-11  表内容换成对数型提亮曲线 k=10（原 S 曲线 P=118 A=B=1.25 对
//               「偏暗 + 光源过亮」方向相反，会越开越暗）。端口/时序/12 路结构均未动。
//   2026-10-11b 表内容换成两段幂函数曲线 P=160 A=B=0.50：对数曲线把 y(236) 抬到 248，
//               与「光源过亮」相反；本曲线 42->82 且 236->213（低于原始），两条诉求同向。
//               端口/时序/12 路结构/旁路行为均未动。
