//               反 S（P=160 A=B=0.50）A、B 都 < 1 ⇒ 两侧都凹，实测【降低】对比度约 26%、
//               画面发灰发闷；真 S A、B 都 > 1 ⇒ 两侧都凸，p10-p90 跨度 165->215、
//               中调斜率 0.695->1.086。黑位 K 由 24 改为 1（真 S 基底只需最小 K 即可满足
//               K=45 时 y(x)=0 一直到 x=40，暗部 16% 的码值被硬削平，
//               既过不了「==0 占比 <= 3%」的验收判据、画面暗部也会成块。
//               y(0)=y(1)=y(2)=0；沿用 K=45 会把 x<=40 全部削成 0）。
//               端口/时序/12 路结构/旁路行为均未动（仍是固定 2 拍）。
