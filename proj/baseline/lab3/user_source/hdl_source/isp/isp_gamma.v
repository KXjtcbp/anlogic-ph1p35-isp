// [HDR-2026-10-11b] 文件      : isp_gamma.v
// 模块      : isp_gamma
// 功能      : ISP 支路的 8bit 色调曲线（tone curve, 两段幂函数）查表级。
//             ★数据格式与上游 awb 完全相同：96 bit = 4 像素 × 24 bit
//               （[23:16]=R [15:8]=G [7:0]=B），一拍 4 个像素、共 12 个 8bit 分量。
//             ★12 个分量共用同一张 256×8 表：R/G/B 同表 ⇒ 只改亮度曲线，
//               不改变三通道比例 ⇒ 不会动白平衡（这正是「压暗部/提亮高光、
//               解决画面发灰」想要的）。
//
// 表        : E:\FPGA\_analysis\gamma_lut_twoseg_p160_a050.hex
//             由 E:\FPGA\_analysis\gen_gamma_lut_twoseg.py 生成，曲线为两段幂函数
//               x <= P : y = P*(x/P)^A
//               x >  P : y = P + (255-P)*(1 - ((255-x)/(255-P))^B)
//               参数 P=160, A=0.50, B=0.50（反 S：提暗部 + 压高光）
//             ★选型依据（2026-10-11 用实拍 31.5x 图离线仿真，见 _analysis/sim_tone3.py）★
//               现状 31.5x 线性      Y均值 46.0 中位 42  暗部<=8 9.91%  过曝>=250 0.036%
//               旧 S 曲线 P118 A=1.25 Y均值 39.0 中位 32  暗部<=8 23.69% 过曝 0.040%
//                                   ^^^ 方向相反：越开越暗、暗部更死 ^^^
//               对数曲线 k=10        Y均值 99.0 中位 103 暗部<=8 0.25%  过曝 0.044%
//                                   ^^^ 提亮够，但 y(236)=248 把光源抬得更亮 ^^^
//               本曲线 P=160 A=0.50   Y均值 79.8 中位 82  暗部<=8 0.19%  过曝>=250 0.024%
//                                   ⇒ 暗部提亮 + 光源本身变暗，两条诉求同向解决
//             ★锚点（本段数字由生成脚本按表自动打印，已逐条核对）★
//               0->0  4->25  8->36  16->51  32->72  42->82  64->101  90->120  118->137  160->160  200->183  236->213  255->255
//             性质：单调不减；最长平台 2 级；暗部提升（42->82，+40 码）；
//               高光压缩（236->213，比原始低 23 码；200->183），y(0)=0 保留真黑，y(255)=255 保留白。
//             ★灰雾风险控制★ 低端斜率 y(4)/4 = 6.25（对数值 k=10 为 4.17），
//               实测该场景 x<=8 的像素占 9.91%，提亮后落到 <=36 码 ⇒ 不会出现大片灰雾。
// 实现      : 12 个独立 256×8 同步读 ROM（(* rom_style="bram" *) 指导 TD 推断成
//             ERAM 硬核块，不吃 LUT/寄存器阵列；若 TD 判不满足条件会自动退回
//             SLICE 实现，功能不变、只是多占 LUT）+ 一级输出寄存器。
//             ROM 与输出级一律无条件推进（不加读使能、不加复位），最容易被
//             推断成 ERAM。
//             ★★tready 处理必须与整条链路一致★★
//               awb.v:513 与 my_algo.v:96 都是 `assign I_tready = O_tready;` 的
//               纯直通，两模块的数据寄存器都【无条件】推进（awb.v:507 的
//               O_tdata 是组合、my_algo.v:374 的 else 分支没有 tready 门控），
//               即全链路【没有真正的反压】，靠「ISP 写入速率与显示侧读取速率
//               天然匹配」保证 video_in FIFO 不满。
//               ⇒ 本级也必须是纯 2 拍流水、绝不允许停拍：
//                 若在这里 stall，上游 awb 仍会照常推进 ⇒ 每停一拍丢一个 beat
//                 ⇒ 画面出现竖向撕裂/错位。故此处照抄同一条
//                 `assign I_tready = O_tready;`。
//
// 延迟      : 固定 2 拍（ROM 同步读 1 拍 + 输出寄存器 1 拍），无空拍。
//             ★在 isp_top.v 里插到 awb 与 my_algo 之间。原厂写法是
//               `assign O_tlast = awb_O_tlast;`（tlast 取「my_algo 输入那一拍」），
//               加本级之后 my_algo 的输入 beat 就是本级的输出 beat，所以
//               isp_top.v 里改成 `assign O_tlast = gam_O_tlast;` ⇒ 与加本级之前
//               语义逐拍等价（等效于把 awb_O_tlast 延 2 拍），行尾标记不会错位。
//
// 旁路      : I_gamma_bypass = 1 时整级直通（表不生效，8bit 数据原样过），
//             上板用 SW2 控制，用于「开/关对比」与故障回退。
//             ★注意：旁路是「整级直通」，延迟仍是 2 拍（不是 0 拍），
//               所以开关切换不会改变流水线深度、不会错帧。
//
// 端口方向约定（与 awb / my_algo / 原厂 edge_detect_96.v 一致）：
//             I_tready 是 output（本级能不能收），O_tready 是 input（下游能不能收）。
//-----------------------------------------------------------------------------
