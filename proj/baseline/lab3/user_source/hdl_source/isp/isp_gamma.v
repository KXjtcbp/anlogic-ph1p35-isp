`timescale 1ns/1ns

module isp_gamma (
    input               I_clk           ,   // 时钟（axi4s_video_aclk = S_csi_rx_clk）
    input               I_rst_n         ,   // 复位，低有效

    //---- 来自 awb 的 96bit 数据流（4 像素 × 24bit）----
    input               I_tlast         ,   // 行结束
    input               I_tuser         ,   // 帧开始
    input  [95:0]       I_tdata         ,   // [23:16]=R [15:8]=G [7:0]=B，一拍 4 像素
    input               I_tvalid        ,   // 数据有效
    output              I_tready        ,   // 本级准备好接受（回压 awb）

    //---- 旁路控制（来自顶层的 SW2，已做过的同步/去抖在顶层）----
    input               I_gamma_bypass  ,   // 1 = 直通（表不生效）；0 = 启用色调曲线

    //---- 送往 my_algo ----
    output [95:0]       O_tdata         ,
    output              O_tlast         ,
    output              O_tuser         ,
    output              O_tvalid        ,
    input               O_tready        // 下游准备好接受
);

