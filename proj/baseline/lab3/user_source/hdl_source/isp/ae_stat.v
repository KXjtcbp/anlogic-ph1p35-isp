//=============================================================================
// [HDR-2026-10-12] 文件 : ae_stat.v   （新建，AE 第 1 步）
// 模块   : ae_stat —— 自动曝光(AE)的帧亮度统计器
// 所在域 : ISP 像素域 S_csi_rx_clk (= MIPI_RX_BYTE_CLK) 60 MHz，与 awb 同域
//-----------------------------------------------------------------------------
// 功能   : 每帧统计四个量，帧末锁存并通过单 bit 翻转交给 24MHz 域：
//            O_luma_sum : Σ (Y * 256)，Y = (77R + 150G + 29B) >> 8
//            O_pix_cnt  : 参与统计的像素数
//            O_hi_cnt   : 「任一通道 >= 250」的像素数（高光护栏用）
//            O_lo_cnt   : 「三个通道都 <= 8」的像素数（暗部护栏用）
//-----------------------------------------------------------------------------
// 数据来源: 与 awb 完全相同的三根线 —— m_axis_tdata_96 / m_axis_tvalid / m_axis_tuser
//           ★刻意不自己另造 valid/tuser 对★：awb 用的就是这一对，实测它的帧统计是
//           对的（ChipWatcher 抓过 sum_r/sum_g/sum_b），所以 AE 与 AWB 看到的是
//           同一条码流，不会出现"两个统计器对不齐"的隐蔽错误。
//-----------------------------------------------------------------------------
// 亮度公式: Y = (77R + 150G + 29B) >> 8，与 _analysis/scripts/stat_imgs.py 一致。
//           ★★ 绝不许出现常数乘法！★★
//           77 / 150 / 29 全部拆成移位+加法。历史事故：my_algo.v 里写 r*77 被 TD
//           推断成 DSP，把整机 DSP 顶到 40/40 用满，进而迫使 hdmi_mixer 的乘法改走
//           LUT，产生 5 个 HDMI 像素域违例 0.018~0.081ns（见 HISTORY.md）。
//           本模块的 40 DSP 预算占用必须保持 0。
//-----------------------------------------------------------------------------
// 面积优化（本模块的两个关键取舍）:
//   1) 亮度不要按 4 个像素各算一次（=12 次移位加法树），而是先把 4 个像素的
//      R/G/B 分别求和（sr/sg/sb，各 10bit），再做一次移位加法树。
//      数学上完全等价（线性），加法器从 12 组降到 3 组。
//   2) 高光/暗部护栏不用亮度判据，改用 max(R,G,B)：
//        hi = (max(R,G,B) >= 250)    ← 这本来就是比亮度更准的削顶指示
//        lo = (max(R,G,B) <=   8)
//      省掉 4 组完整的亮度计算。
//   ⇒ 整模块预计 ~250 LUT / ~110 FF / 0 DSP / 0 ERAM。
//      注意当前整机 slice 已用 83.37%（#slices 17687/21216），余量只有 16.6%，
//      所以这里的面积优化不是可选项。
//-----------------------------------------------------------------------------
// 跨域协议（单 bit 翻转，与 key_mode_ctrl.v 同一套做法）:
//   O_frame_tgl 每帧末翻转一次。60Hz 帧率 ⇒ 30Hz 方波，24MHz 域能稳定采样
//   （★不能用手持脉冲★：60MHz 下一个周期的脉冲只有 16.7ns，24MHz 时钟周期
//    41.7ns，会整个漏掉）。
//   O_* 数据寄存器从"翻转沿"到"下一帧末"保持 ~16.7ms 不变；24MHz 域用两级
//   同步器 + 边沿检测后再读，距离数据更新至少 2 个 24MHz 周期（83ns），
//   而数据在其后 16.7ms 内不会再变 ⇒ 采样窗口余量约 200000 倍，不需要握手。
//-----------------------------------------------------------------------------
// 参数   : NOM_PIX —— 标称每帧像素数（1280*720 = 921600 像素 = 230400 拍 × 4）。
//          只用于文档/自检；真正的除法由 ae_ctrl 用"固定阈值比较"回避（AE 是闭环，
//          常系数缩放只会平移有效目标，不影响收敛）。
//-----------------------------------------------------------------------------
// 复位   : 低有效。复位后所有输出为 0、O_frame_tgl = 0。
// 依赖   : 无（纯逻辑，不例化任何 IP、不用 $readmemh、不引入 ROM）
//=============================================================================

module ae_stat #(
    parameter NOM_PIX   = 32'd230400,     // 标称每帧拍数(230400 拍 × 4 像素/拍)
    parameter HI_THRESH = 8'd250,         // 高光判据：max(R,G,B) >= 此值
    parameter LO_THRESH = 8'd8            // 暗部判据：max(R,G,B) <= 此值
)(
    input  wire        I_clk,
    input  wire        I_rst_n,

    // 与 awb 同源的三根线
    input  wire        I_tvalid,
    input  wire        I_tuser,           // 帧首，每帧一次
    input  wire [95:0] I_tdata,           // 4 像素/拍，pix0=[23:0] pix3=[95:72]

    // 帧统计结果（保持到下一帧末）
    output reg  [39:0] O_luma_sum,        // Σ (Y * 256)
    output reg  [31:0] O_pix_cnt,         // 参与统计的像素数
    output reg  [31:0] O_hi_cnt,          // 任一通道 >= HI_THRESH 的像素数
    output reg  [31:0] O_lo_cnt,          // 三通道都   <= LO_THRESH 的像素数

    // 跨域握手：每帧末翻转一次
    output reg         O_frame_tgl
);

    //------------------------------------------------------------------------
    // 1) 4 像素的 R / G / B 分别求和（10bit）
    //    位域（与 isp_gamma.v / awb.v 一致）：每像素 {R[23:16], G[15:8], B[7:0]}
    //------------------------------------------------------------------------
    wire [9:0] sr = I_tdata[23:16] + I_tdata[47:40] + I_tdata[71:64] + I_tdata[95:88];
    wire [9:0] sg = I_tdata[15:8]  + I_tdata[39:32] + I_tdata[63:56] + I_tdata[87:80];
    wire [9:0] sb = I_tdata[7:0]   + I_tdata[31:24] + I_tdata[55:48] + I_tdata[79:72];

    //------------------------------------------------------------------------
    // 2) 一次移位加法树：77*sr + 150*sg + 29*sb
    //    77  = 64+8+4+1     -> (sr<<6)+(sr<<3)+(sr<<2)+sr
    //    150 = 128+16+4+2   -> (sg<<7)+(sg<<4)+(sg<<2)+(sg<<1)
    //    29  = 16+8+4+1     -> (sb<<4)+(sb<<3)+(sb<<2)+sb
    //    最大 256*1020 = 261120，18bit 足够
    //------------------------------------------------------------------------
    wire [17:0] luma_beat =
          ( (sr << 6) + (sr << 3) + (sr << 2) + sr        )
        + ( (sg << 7) + (sg << 4) + (sg << 2) + (sg << 1) )
        + ( (sb << 4) + (sb << 3) + (sb << 2) + sb        );

    //------------------------------------------------------------------------
    // 3) 高光 / 暗部判据：max(R,G,B) 的 4 个像素
    //------------------------------------------------------------------------
    function [7:0] max3;
        input [7:0] a;
        input [7:0] b;
        input [7:0] c;
        reg   [7:0] m;
        begin
            m   = (a > b) ? a : b;
            max3 = (m > c) ? m : c;
        end
    endfunction

    wire [7:0] mx0 = max3(I_tdata[23:16], I_tdata[15:8], I_tdata[7:0]);
    wire [7:0] mx1 = max3(I_tdata[47:40], I_tdata[39:32], I_tdata[31:24]);
    wire [7:0] mx2 = max3(I_tdata[71:64], I_tdata[63:56], I_tdata[55:48]);
    wire [7:0] mx3 = max3(I_tdata[95:88], I_tdata[87:80], I_tdata[79:72]);

    wire [2:0] hi_beat = { 2'b00, (mx0 >= HI_THRESH) }
                       + { 2'b00, (mx1 >= HI_THRESH) }
                       + { 2'b00, (mx2 >= HI_THRESH) }
                       + { 2'b00, (mx3 >= HI_THRESH) };

    wire [2:0] lo_beat = { 2'b00, (mx0 <= LO_THRESH) }
                       + { 2'b00, (mx1 <= LO_THRESH) }
                       + { 2'b00, (mx2 <= LO_THRESH) }
                       + { 2'b00, (mx3 <= LO_THRESH) };

    //------------------------------------------------------------------------
    // 4) 帧累加 + 帧末发布
    //    I_tuser 那一拍同时扮演两个角色：
    //      (a) 把上一帧的累加结果发布到 O_*（因为此刻上一帧刚好结束）
    //      (b) 用当前拍复位累加器（tuser 拍本身也要计入本帧）
    //    ★与 awb.v:139-145 的 `if(!I_rst_n || I_tuser) ... <= 0` 同一约定★
    //------------------------------------------------------------------------
    reg [39:0] acc_sum;
    reg [31:0] acc_cnt;
    reg [31:0] acc_hi;
    reg [31:0] acc_lo;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            acc_sum     <= 40'd0;
            acc_cnt     <= 32'd0;
            acc_hi      <= 32'd0;
            acc_lo      <= 32'd0;
            O_luma_sum  <= 40'd0;
            O_pix_cnt   <= 32'd0;
            O_hi_cnt    <= 32'd0;
            O_lo_cnt    <= 32'd0;
            O_frame_tgl <= 1'b0;
        end
        else if (I_tuser) begin
            // (a) 发布刚结束的那一帧
            O_luma_sum  <= acc_sum;
            O_pix_cnt   <= acc_cnt;
            O_hi_cnt    <= acc_hi;
            O_lo_cnt    <= acc_lo;
            O_frame_tgl <= ~O_frame_tgl;
            // (b) 用当前拍作为新帧的第一拍
            acc_sum     <= I_tvalid ? { 22'd0, luma_beat } : 40'd0;
            acc_cnt     <= I_tvalid ? 32'd4               : 32'd0;
            acc_hi      <= I_tvalid ? { 29'd0, hi_beat  }  : 32'd0;
            acc_lo      <= I_tvalid ? { 29'd0, lo_beat  }  : 32'd0;
        end
        else if (I_tvalid) begin
            acc_sum <= acc_sum + { 22'd0, luma_beat };
            acc_cnt <= acc_cnt + 32'd4;
            acc_hi  <= acc_hi  + { 29'd0, hi_beat };
            acc_lo  <= acc_lo  + { 29'd0, lo_beat };
        end
    end

endmodule
