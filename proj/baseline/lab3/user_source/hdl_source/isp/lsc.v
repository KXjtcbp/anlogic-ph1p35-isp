//-----------------------------------------------------------------------------
//  坐标：每行 beat 计数 + 行计数
//  ★这里只数 valid 拍，因为 MIPI→ISP 这条流的 tvalid 是有空隙的（实测
//    占空比约 2/3），不能拿 clk 计数代替。★
//-----------------------------------------------------------------------------
    reg [8:0]  S_bx;      // 0 .. H_BEATS-1（320 需 9 bit）
    reg [11:0] S_y;       // 0 .. V_LINES-1

    wire S_line_end  = I_tvalid & I_tlast;
    wire S_beat_last = (S_bx == (H_BEATS[8:0] - 9'd1)) | S_line_end;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            S_bx <= 9'd0;
            S_y  <= 12'd0;
        end
        else if (I_tuser) begin           // 帧起始：行列都归零
            S_bx <= 9'd0;
            S_y  <= 12'd0;
        end
        else if (I_tvalid) begin
            if (S_line_end) begin
                S_bx <= 9'd0;
                S_y  <= (S_y == (V_LINES - 12'd1)) ? 12'd0 : (S_y + 12'd1);
            end
            else begin
                S_bx <= S_beat_last ? S_bx : (S_bx + 9'd1);
            end
        end
    end

    // [HDR-2026-10-14] 改成完整二维表：
    //   水平 = bx / 16 = bx[8:4]（0..19，每节点 64 像素）
    //   垂直 = y  / 64 = y[11:6]（0..11，每节点 64 行）
    wire [4:0] S_hidx = S_bx[8:4];
    wire [3:0] S_vidx = S_y[11:6];

    //-----------------------------------------------------------------------------
    //  完整二维取值：kR / kB 各自一张表（不再是 KH[x]+KV[y] 的分离式）
    //  ★为什么换★：可分离版只吃掉 20% 的碗（实测逐列极差 0.085 -> 0.068），
    //  二维表有 20x12 = 240 个自由参数，是分离式 43 个的 5.6 倍。
    //  仍然不引入乘法器 / BRAM：240 项 8bit 常数被 TD 综合成纯 LUT ROM。
    //-----------------------------------------------------------------------------
    wire [7:0] S_k2 = F_k2d(S_vidx, S_hidx);
    wire [3:0] S_kr = S_k2[7:4];
    wire [3:0] S_kb = S_k2[3:0];

//-----------------------------------------------------------------------------
//  第 1 级流水：锁存 k 与像素数据
