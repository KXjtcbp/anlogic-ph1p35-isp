//-----------------------------------------------------------------------------
//  移位加法树：p = v * kq
//  ★2026-10-14 第三次改：kq 从 4bit 提到 10bit（1/1024 增益单位）★
//  乘数 kq 的 10 个位各自对应 v 的一个移位，按位条件相加得到 p。
//  全是 LUT 加法器 —— 不用乘法器（HISTORY 第 2 条：常数乘法被 TD 推断成 DSP，
//  曾把整机 40 个 DSP 一次顶满）、不用 BRAM。
//  位宽核算：v<=255、kq<=1023 => p <= 260865 < 2^18，故 r 取 18 bit。
//  16 个 F_apply 实例（4 像素 x R/B x 2 级）共用这段逻辑，TD 会自动复用。
//-----------------------------------------------------------------------------
    function [17:0] F_mul(input [7:0] v, input [9:0] kq);
        reg [17:0] r;
        begin
            r = 18'd0;
            if (kq[0]) r = r + {10'b0000000000, v        };
            if (kq[1]) r = r + { 9'b000000000,  v, 1'b0  };
            if (kq[2]) r = r + { 8'b00000000,   v, 2'b00 };
            if (kq[3]) r = r + { 7'b0000000,    v, 3'b000};
            if (kq[4]) r = r + { 6'b000000,     v, 4'b0000};
            if (kq[5]) r = r + { 5'b00000,      v, 5'b00000};
            if (kq[6]) r = r + { 4'b0000,       v, 6'b000000};
            if (kq[7]) r = r + { 3'b000,        v, 7'b0000000};
            if (kq[8]) r = r + { 2'b00,         v, 8'b00000000};
            if (kq[9]) r = r + { 1'b0,          v, 9'b000000000};
            F_mul = r;
        end
    endfunction

    // g = 1 + kq/1024  =>  out = v + ((v*kq) >> 10)，饱和到 255
    function [7:0] F_apply(input [7:0] v, input [9:0] kq);
        reg [17:0] p;
        reg [8:0]  s;
        begin
            p = F_mul(v, kq);
            s = {1'b0, v} + {1'b0, p[17:10]};   // 1/1024 单位，右移 10 位
            F_apply = s[8] ? 8'd255 : s[7:0];
        end
    endfunction

//-----------------------------------------------------------------------------
//  第 2 级流水：4 像素 x 2 通道（R 与 B）
//  像素 j 的 R 在 bit[24j+16 +: 8]、B 在 bit[24j +: 8]、G 在 bit[24j+8 +: 8]
//-----------------------------------------------------------------------------
    wire [7:0] r0 = S_d_r[23:16], g0 = S_d_r[15: 8], b0 = S_d_r[ 7: 0];
    wire [7:0] r1 = S_d_r[47:40], g1 = S_d_r[39:32], b1 = S_d_r[31:24];
    wire [7:0] r2 = S_d_r[71:64], g2 = S_d_r[63:56], b2 = S_d_r[55:48];
    wire [7:0] r3 = S_d_r[95:88], g3 = S_d_r[87:80], b3 = S_d_r[79:72];

    wire [7:0] r0c = F_apply(r0, S_kr_r), b0c = F_apply(b0, S_kb_r);
    wire [7:0] r1c = F_apply(r1, S_kr_r), b1c = F_apply(b1, S_kb_r);
    wire [7:0] r2c = F_apply(r2, S_kr_r), b2c = F_apply(b2, S_kb_r);
    wire [7:0] r3c = F_apply(r3, S_kr_r), b3c = F_apply(b3, S_kb_r);

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            O_tdata <= 96'd0;
            O_tvalid <= 1'b0;
            O_tuser  <= 1'b0;
            O_tlast  <= 1'b0;
        end
        else begin
            // G 三路原样直通；R/B 用校正后的值
            O_tdata <= { r3c, g3, b3c,
                         r2c, g2, b2c,
                         r1c, g1, b1c,
                         r0c, g0, b0c };
            O_tvalid <= S_v1;
            O_tuser  <= S_u1;
            O_tlast  <= S_l1;
        end
    end

