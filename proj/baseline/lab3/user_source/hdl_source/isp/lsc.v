            S_kr_r <= 4'd0;
            S_kb_r <= 4'd0;
            S_d_r <= 96'd0;
            S_v1  <= 1'b0;
            S_u1  <= 1'b0;
            S_l1  <= 1'b0;
        end
        else begin
            S_kr_r <= I_bypass ? 4'd0 : S_kr;
            S_kb_r <= I_bypass ? 4'd0 : S_kb;
            S_d_r <= I_tdata;
            S_v1  <= I_tvalid;
            S_u1  <= I_tuser;
            S_l1  <= I_tlast;
        end
    end

//-----------------------------------------------------------------------------
//  移位加法树：p = v * k，k 只有 0..7
//  用 v 的移位组合代替乘法器 —— 8bit 输入、10bit 结果，全部是 LUT 加法器。
//  乘数只有 4bit，先拆成"2 的幂"再相加。
//-----------------------------------------------------------------------------
    function [11:0] F_mul(input [7:0] v, input [3:0] k);
        reg [11:0] a, b, c, d, r;
        begin
            // [HDR-2026-10-14] 重写：
            //  a) 位宽 10 -> 12。原写法 p = v*k 最大 7*255 = 1785 > 1023 会回绕，
            //     回绕后 p[9:6] 反而变小 => v > 146 的像素校正被抹掉（真 bug）。
            //  b) 支持 k = 0..15（原来是 case 到 7，>7 全按 7 处理），g 上限从 1.1094 提到 1.234。
            //     k 的每一级仍是 1/64 = 1.56%，量化更细。
            //  4 个移位项按 k 的 4 个位做条件相加，全是 LUT 加法器，不用乘法器/BRAM。
            a = {4'b0000, v};               // v * 1
            b = {3'b000, v, 1'b0};          // v * 2
            c = {2'b00, v, 2'b00};          // v * 4
            d = {1'b0, v, 3'b000};          // v * 8
            r = 12'd0;
            if (k[0]) r = r + a;
            if (k[1]) r = r + b;
            if (k[2]) r = r + c;
            if (k[3]) r = r + d;
            F_mul = r;
        end
    endfunction

    // g = 1 + k/64  =>  out = v + ((v*k) >> 6)，饱和到 255
    function [7:0] F_apply(input [7:0] v, input [3:0] k);
        reg [11:0] p;
        reg [8:0] s;
        begin
            p = F_mul(v, k);
            s = {1'b0, v} + {1'b0, p[11:6]};    // v + p/64 => g = 1 + k/64（k 到 15）
            F_apply = s[8] ? 8'd255 : s[7:0];
        end
    endfunction

//-----------------------------------------------------------------------------
//  第 2 级流水：4 像素 x 2 通道（R 与 B）
//  像素 j 的 R 在 bit[24j+16 +: 8]、B 在 bit[24j +: 8]、G 在 bit[24j+8 +: 8]
//-----------------------------------------------------------------------------
    wire [7:0] r0 = S_d_r[23:16], g0 = S_d_r[15: 8], b0 = S_d_r[ 7: 0];
    wire [7:0] r1 = S_d_r[47:40], g1 = S_d_r[39:32], b1 = S_d_r[31:24];
    wire [7:0] r2 = S_d_r[71:64], g2 = S_d_r[63:56], b2 = S_d_r[55:48];
    wire [7:0] r3 = S_d_r[95:88], g3 = S_d_r[87:80], b3 = S_d_r[79:72];

    wire [7:0] r0c = F_apply(r0, S_kr_r), b0c = F_apply(b0, S_kb_r);
    wire [7:0] r1c = F_apply(r1, S_kr_r), b1c = F_apply(b1, S_kb_r);
    wire [7:0] r2c = F_apply(r2, S_kr_r), b2c = F_apply(b2, S_kb_r);
    wire [7:0] r3c = F_apply(r3, S_kr_r), b3c = F_apply(b3, S_kb_r);

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            O_tdata <= 96'd0;
            O_tvalid <= 1'b0;
            O_tuser  <= 1'b0;
            O_tlast  <= 1'b0;
        end
        else begin
            // G 三路原样直通；R/B 用校正后的值
            O_tdata <= { r3c, g3, b3c,
                         r2c, g2, b2c,
                         r1c, g1, b1c,
                         r0c, g0, b0c };
            O_tvalid <= S_v1;
            O_tuser  <= S_u1;
            O_tlast  <= S_l1;
        end
    end

